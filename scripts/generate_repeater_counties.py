COUNTY_SUFFIXES = (
    " city and borough",
    " census area",
    " municipality",
    " municipio",
    " county",
    " parish",
    " borough",
)


def _display_name(name: str) -> str:
    normalized = name.strip()
    for suffix in COUNTY_SUFFIXES:
        if normalized.casefold().endswith(suffix):
            normalized = normalized[: -len(suffix)].rstrip()
            break
    if normalized.endswith(" city"):
        normalized = normalized[: -len(" city")].rstrip()
    return normalized


def _dart_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _read_source(path: Path | None) -> tuple[bytes, bytes]:
    if path is None:
        with urllib.request.urlopen(SOURCE_URL, timeout=60) as response:
            archive = response.read()
    else:
        archive = path.read_bytes()

    if zipfile.is_zipfile(io.BytesIO(archive)):
        with zipfile.ZipFile(io.BytesIO(archive)) as bundle:
            text_name = next(
                name for name in bundle.namelist() if name.endswith(".txt")
            )
            census_csv = bundle.read(text_name)
    else:
        census_csv = archive
    return archive, census_csv


def generate(census_csv: bytes, source_sha256: str) -> str:
    lines = census_csv.decode("utf-8-sig").splitlines()
    header = lines[0].split("\t")
    state_index = header.index("USPS")
    name_index = header.index("NAME")
    counties: dict[str, set[str]] = {}

    for line in lines[1:]:
        fields = line.split("\t")
        state_code = fields[state_index].strip()
        state_name = STATE_NAMES.get(state_code)
        if state_name is None:
            continue
        county = _display_name(fields[name_index])
        if county:
            counties.setdefault(state_name, set()).add(county)

    missing = sorted(set(STATE_NAMES.values()) - counties.keys())
    if missing:
        raise ValueError("Census data is missing states: %s" % ", ".join(missing))

    output = [
        "// Code generated by scripts/generate_repeater_counties.py; "
        "DO NOT EDIT.",
        "// Source: U.S. Census Bureau 2024 County Gazetteer",
        "// %s" % SOURCE_URL,
        "// ZIP SHA-256: %s" % source_sha256,
        "",
        "const repeaterUsCountiesByState = <String, List<String>>{",
    ]
    for state in sorted(counties, key=str.casefold):
        output.append("  %s: <String>[" % _dart_string(state))
        for county in sorted(counties[state], key=str.casefold):
            output.append("    %s," % _dart_string(county))
        output.append("  ],")
    output.extend(["};", ""])
    return "\n".join(output)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("lib/models/repeater_counties.dart"),
    )
    args = parser.parse_args()

    archive, census_csv = _read_source(args.input)
    source_sha256 = hashlib.sha256(archive).hexdigest()
    args.output.write_text(generate(census_csv, source_sha256), encoding="utf-8")
    print("Wrote %s" % args.output)


if __name__ == "__main__":
    main()
